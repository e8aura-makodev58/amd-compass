import {test,expect} from '@playwright/test';
const api='/api/control-rooms/plant-1';
for (const width of [375,1280]) test(`fix recommendations, evidence and applied audit survive provider failure at ${width}px`, async({page})=>{
 await page.setViewportSize({width,height:900});
 await page.request.post(`${api}/reset`);
 await page.goto('/rooms/plant-1');
 await page.locator('#issue-list').getByRole('button',{name:/ISS-104/}).click();
 const fix=page.locator('#issue-summary .fix-panel');
 await expect(fix.getByRole('heading',{name:'Recommended fix',exact:true})).toBeVisible();
 await expect(fix).toContainText('Source: Deterministic');
 await expect(fix).toContainText('Observed symptom:');
 await fix.getByText('Troubleshooting order and evidence',{exact:true}).click();
 await expect(fix.locator('table')).toContainText('Smoothed success');
 await expect(fix.locator('tbody tr')).toHaveCount(6);
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1)).toBe(true);
 await page.request.post(`${api}/compass/recommend`,{data:{issueId:'ISS-104'}});
 await page.request.post(`${api}/simulation/speed`,{data:{speed:60}});
 await page.request.post(`${api}/simulation/start`);
 await expect.poll(async()=>{const s=await(await page.request.get(`${api}/state`)).json();return s.issues.find(i=>i.id==='ISS-104')?.status;},{timeout:15000}).toBe('ASSIGNED');
 await page.request.post(`${api}/issues/ISS-104/force-resolve`);
 await page.request.post(`${api}/simulation/pause`);
 const audit=await(await page.request.get(`${api}/issues/ISS-104/audit`)).json();
 expect(audit.resolutionHistory.some(r=>r.fixApplied?.id?.startsWith('FIX-B-'))).toBe(true);
 expect(JSON.stringify(audit)).not.toMatch(/faultTruth|hidden-cause-|trueSuccessProbability|successMultiplier/);
 await page.reload();
 await page.locator('[data-feed-issue-id="ISS-104"]').first().click();
 await expect(page.locator('#recommendation-panel')).toContainText('Applied fixes by attempt');
 await expect(page.locator('#recommendation-panel')).toContainText(/FIX-B-/);
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1)).toBe(true);
 expect(await page.locator('#recommendation-panel').evaluate(el=>el.scrollWidth<=el.clientWidth+1)).toBe(true);
 await page.getByRole('button',{name:'Analytics',exact:true}).click();
 await expect(page.getByRole('heading',{name:'Fix recommendations and outcomes',exact:true})).toBeVisible();
 await expect(page.locator('#analytics-content')).toContainText('First-time fix rate');
});
